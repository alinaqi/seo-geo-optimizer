"""Build a self-contained plan.html from an audit output directory so the owner can review
and decide on each item in any browser (no hosted artifacts, no external resources).
Usage: python scripts/html_plan.py --outdir audit/ [--strategy strategy/] [--out audit/plan.html]"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))  # allow `python scripts/x.py`
import argparse
import html
from scripts import report as rp
from scripts.html_sections import calendar_section, load, md, report_section, section
from scripts.html_theme import CSS, JS

DECISIONS = ["pending", "approve", "defer", "reject"]


def _plan_rows(items):
    opts = "".join(f'<option value="{d}">{d}</option>' for d in DECISIONS)
    rows = []
    for n, it in enumerate(items, 1):
        rows.append(f'<tr data-item="{n}"><td class="num">{n}</td><td><strong>{it["strategy"]}</strong> {html.escape(it["name"])}</td>'
                    f'<td>{html.escape(it["finding"])}</td><td class="num">{it["priority"]}</td>'
                    f'<td><select class="decision">{opts}</select></td><td><input class="note" placeholder="note for the agent"></td></tr>')
    return "\n".join(rows)


def _plan_section(outdir):
    items = rp.build_plan(load(outdir, "audit.json"), load(outdir, "lint.json"), load(outdir, "schema.json"))
    toolbar = ('<div class="toolbar"><button id="copy" type="button">Copy decisions</button><button id="reset" type="button">Reset</button>'
               '<span id="status">Mark each item, then copy the decisions and paste them to your agent.</span></div>'
               '<textarea id="export" hidden rows="8" style="width:100%"></textarea>')
    table = ('<div class="tbl"><table><thead><tr><th>#</th><th>Strategy</th><th>Finding</th><th>Priority</th><th>Decision</th><th>Note</th></tr></thead>'
             f'<tbody>{_plan_rows(items)}</tbody></table></div>'
             '<p class="legend">Priority = win probability x impact x (4 - risk) / effort. Decisions stay in this browser until you copy them.</p>')
    return section("review", "Review and decide", toolbar + table)


def _page(title, sections):
    nav = "".join(f'<a href="#{s.split(chr(34))[1]}">{s.split("<h2>")[1].split("</h2>")[0]}</a>' for s in sections if s)
    return ("<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
            f"<title>{html.escape(title)}</title><style>{CSS}</style></head><body><div class=\"wrap\"><header><h1>{html.escape(title)}</h1>"
            "<p>Generated by seo-geo-optimizer. Open in any browser; nothing leaves this file.</p></header>"
            f"<nav>{nav}</nav>{''.join(sections)}<footer>Evidence grades, strategy IDs and gates are defined in references/strategies.md. "
            "Items marked UNKNOWN were not verifiable by the agent; a human confirms them.</footer></div>"
            f"<script>{JS}</script></body></html>")


def build(outdir, strategy_dir=None):
    outdir = Path(outdir)
    url = load(outdir, "audit.json").get("url", outdir.name)
    sections = [_plan_section(outdir), calendar_section(strategy_dir or outdir), report_section(outdir)]
    return _page(f"SEO + GEO plan: {url}", sections)


def render_markdown_page(title, text):
    return _page(title, [section("body", title, md(text))]).replace(f"<script>{JS}</script>", "")


def write(outdir, strategy_dir=None, out=None):
    out = Path(out) if out else Path(outdir) / "plan.html"
    out.write_text(build(outdir, strategy_dir))
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--outdir", default="audit")
    ap.add_argument("--strategy", default=None)
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    print("wrote", write(a.outdir, a.strategy, a.out))


if __name__ == "__main__":
    main(sys.argv[1:])
